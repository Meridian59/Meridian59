#!/usr/bin/env python3
"""Writes a module's exports by ordinal, from its .def file and the symbols its
object files define, as a C table GetProcAddress reads (m59_ordinal_exports),
with the module's DllMain for LoadLibrary.

The functions are C++ (the sources compile as C++), so their symbols are
mangled: each .def name is found as its plain or mangled symbol, and the table
refers to it by that assembler name.

usage: defexports.py <file.def> <nm> <out.c> <object>...
"""

import re
import subprocess
import sys


def def_exports(path):
    exports, in_exports = [], False
    for line in open(path, encoding='latin-1'):
        line = line.split(';', 1)[0].strip()
        if not line:
            continue
        if re.match(r'^[A-Z]+\b', line) and not line.startswith('@'):
            word = line.split()[0]
            if word in ('EXPORTS', 'LIBRARY', 'DESCRIPTION', 'HEAPSIZE', 'STACKSIZE', 'SECTIONS', 'VERSION'):
                in_exports = word == 'EXPORTS'
                continue
        if in_exports:
            m = re.match(r'^(\w+)(?:\s*=\s*\w+)?\s*(?:@\s*(\d+))?', line)
            if m:
                exports.append((m.group(1), int(m.group(2)) if m.group(2) else 0))
    return exports


def defined_symbols(nm, objects):
    out = subprocess.run([nm, '-g', '--defined-only'] + objects if not sys.platform == 'darwin'
                         else [nm, '-g', '-U'] + objects, capture_output=True, text=True, check=True).stdout
    symbols = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 3 and parts[1] in 'TtWw':
            symbols.add(parts[2])
    return symbols


def find(name, symbols):
    # Mach-O prefixes every C symbol with an underscore.
    for prefix in ('', '_'):
        if prefix + name in symbols:
            return prefix + name
        mangled = '%s_Z%d%s' % (prefix, len(name), name)
        for s in sorted(symbols):
            if s.startswith(mangled) and (len(s) == len(mangled) or not s[len(mangled)].isalnum() or
                                          s[len(mangled)].isupper() or s[len(mangled)] in 'vPRKicslfdbjtmyhaxeEz'):
                return s
    return None


def main():
    def_file, nm, out, objects = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
    symbols = defined_symbols(nm, objects)
    lines = ['/* Generated by win32/tools/defexports.py from %s. */' % def_file.replace('\\', '/'), '']
    entries = []
    exports = def_exports(def_file)
    # The loader's entry point too, which LoadLibrary calls; ordinal 0, not exported.
    if find('DllMain', symbols) and not any(name == 'DllMain' for name, _ in exports):
        exports.append(('DllMain', 0))
    for i, (name, ordinal) in enumerate(exports):
        symbol = find(name, symbols)
        if symbol is None:
            sys.exit('%s: %s is exported but not defined' % (def_file, name))
        lines.append('extern char m59_export_%d __asm__("%s");' % (i, symbol))
        entries.append('   {%d, "%s", &m59_export_%d},' % (ordinal, name, i))
    lines += ['',
              'struct m59_ordinal_export { unsigned short ordinal; const char *name; const void *address; };',
              '__attribute__((visibility("default"))) const struct m59_ordinal_export m59_ordinal_exports[] = {']
    lines += entries + ['   {0, 0, 0},', '};', '']
    text = '\n'.join(lines)
    try:
        if open(out).read() == text:
            return
    except OSError:
        pass
    open(out, 'w').write(text)


main()
