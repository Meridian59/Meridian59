#!/usr/bin/env python3
"""fonttables.py <fontprobe output> <out.inc>: Windows' font tables for
core/fontmap.cpp, from what win32/tools/fontprobe.c measures on Windows.

Raster faces: their sizes, and the size and integer scales (vertical,
horizontal) GDI realizes for each height from -100 to 100 (runs).  TrueType faces: their OS/2 values, and
for each height the difference of GDI's (hinted) ascent, descent, internal
leading and average width from the unhinted values, a letter each ('M' is
none, 'L' one less, 'N' one more)."""
import csv, math, sys

src, dst = sys.argv[1], sys.argv[2]
rows = list(csv.reader(open(src, encoding='utf-8')))
req = {(r[6], int(r[2]), int(r[3]), int(r[1])): r for r in rows if r[0] == 'req'}
os2 = {(r[1], int(r[2])): dict(zip(('upem', 'win_ascent', 'win_descent', 'avg'), map(int, r[3:7])))
       for r in rows if r[0] == 'os2'}

RASTER = [('MS Sans Serif', 0), ('MS Serif', 0), ('Small Fonts', 0), ('Courier', 0), ('Fixedsys', 0),
          ('System', 0), ('Terminal', 255)]
TRUETYPE = ['Arial', 'Times New Roman', 'Courier New', 'Tahoma', 'Microsoft Sans Serif', 'MS Shell Dlg', 'Verdana',
            'Segoe UI']
HEIGHTS = list(range(-100, 0)) + list(range(1, 101))
out = ['// Generated by win32/tools/fonttables.py from win32/tools/fontprobe.c\'s output on',
       '// Windows 11 at 96 dpi: what GDI realizes.  Don\'t edit; measure again.', '']

def name(face): return face.lower().replace(' ', '_')
# As core/fontmap.cpp rounds (std::lround; Python's round goes to even).
def rnd(x): return math.floor(x + 0.5)

# Raster faces.
for face, cs in RASTER:
    metrics = lambda r: tuple(map(int, (r[8], r[9], r[11], r[12], r[13], r[14], r[15])))  # h asc il el avg max wt
    sizes, runs = [], []
    for h in range(-100, 101):
        r = req.get((face, 400, cs, h))
        if r is None: continue
        m = metrics(r)
        # The size it is a scale of, by integer factors: vertical (the smallest
        # that fits), and horizontal for the widths (the same, where it can be).
        sizelist = [tuple(map(int, (r2[3], r2[4], r2[6], r2[7], r2[8], r2[9], r2[10]))) for r2 in rows
                    if r2[0] == 'size' and r2[1] == face]
        found = None
        for k in range(1, 9):
            if any(x % k for x in m[:4]): continue
            for x in sorted(range(1, 9), key=lambda x: (x != k, x)):
                for b in sizelist:
                    if b[:4] == (m[0] // k, m[1] // k, m[2] // k, m[3] // k) and b[4] * x == m[4]:
                        found = (b, k, x); break
                if found: break
            if found: break
        if found is None:
            sys.exit('%s %d: no size scales to %s' % (face, h, m))
        base, k, kx = found
        if base not in sizes: sizes.append(base)
        if runs and runs[-1][2:] == [base, k, kx] and runs[-1][1] == h - 1: runs[-1][1] = h
        else: runs.append([h, h, base, k, kx])
    # Every size, used or not: a width asked for picks among a height's.
    for r2 in rows:
        if r2[0] == 'size' and r2[1] == face:
            b = tuple(map(int, (r2[3], r2[4], r2[6], r2[7], r2[8], r2[9], r2[10])))
            if b not in sizes: sizes.append(b)
    sizes.sort()
    runs = [[a, b, sizes.index(base), k, kx] for a, b, base, k, kx in runs]
    out.append('const RasterSize %s_sizes[] = {' % name(face))
    out += ['   {%d, %d, %d, %d, %d, %d, %d},' % s for s in sizes]
    out.append('};')
    out.append('const RasterRun %s_runs[] = {' % name(face))
    line = '  '
    for a, b, i, k, kx in runs:
        item = ' {%d, %d, %d, %d, %d},' % (a, b, i, k, kx)
        if len(line) + len(item) > 118: out.append(line); line = '  '
        line += item
    out.append(line)
    out += ['};', '']
out.append('const RasterFace raster_faces[] = {')
for face, cs in RASTER:
    out.append('   {"%s", %d, %s_sizes, std::size(%s_sizes), %s_runs, std::size(%s_runs)},' %
               (face, cs, name(face), name(face), name(face), name(face)))
out += ['};', '']

# TrueType faces.
def digits(face, wt, field):
    d = os2[(face, wt)]
    s = ''
    for h in HEIGHTS:
        r = req[(face, wt, 0, h)]
        em = -h if h < 0 else h * d['upem'] / (d['win_ascent'] + d['win_descent'])
        scale = em / d['upem']
        height = int(r[8])
        ref = {'ascent': rnd(d['win_ascent'] * scale), 'descent': rnd(d['win_descent'] * scale),
               'internal': height - rnd(em), 'average': max(1, rnd(d['avg'] * scale))}[field]
        got = int({'ascent': r[9], 'descent': r[10], 'internal': r[11], 'average': r[13]}[field])
        delta = got - ref
        if not -12 <= delta <= 13: sys.exit('%s %d %d %s: %d off' % (face, wt, h, field, delta))
        s += chr(ord('M') + delta)
    return s
for face in TRUETYPE:
    for wt in (400, 700):
        for field in ('ascent', 'descent', 'internal', 'average'):
            s = digits(face, wt, field)
            out.append('const char %s_%d_%s[] =' % (name(face), wt, field))
            for i in range(0, len(s), 100):
                out.append('   "%s"%s' % (s[i:i + 100], ';' if i + 100 >= len(s) else ''))
    out.append('')
# The line gap GDI's external leading is from (hhea's, over the win ascent and
# descent), in font units: the value that gives the measured leading.
def external(face):
    upem = os2[(face, 400)]['upem']
    def fits(e):
        return all(int(r[12]) == max(0, rnd(e * (int(r[8]) - int(r[11])) / upem))
                   for (f, w, c, h), r in req.items() if f == face and c == 0)
    for e in range(0, 1000):
        if fits(e): return e
    sys.exit('%s: no line gap fits' % face)
out.append('const TrueTypeFace truetype_faces[] = {')
for face in TRUETYPE:
    r, b = os2[(face, 400)], os2[(face, 700)]
    n = name(face)
    out.append('   {"%s", %d, %d, %d, %d, {%d, %d},' % (face, r['upem'], r['win_ascent'], r['win_descent'], external(face),
                                                      r['avg'], b['avg']))
    for field in ('ascent', 'descent', 'internal', 'average'):
        out.append('    {%s_400_%s, %s_700_%s}%s' % (n, field, n, field, '},' if field == 'average' else ','))
out.append('};')
open(dst, 'w').write('\n'.join(out) + '\n')
